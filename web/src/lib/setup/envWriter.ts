import fs from "fs";
import path from "path";

export interface EnvVariables {
  supabaseUrl: string;
  anonKey?: string;
  serviceRoleKey: string;
}

/**
 * Writes or updates .env files in web (.env.local) and root (.env).
 * Per JobTrack architecture, ONLY Supabase connection credentials belong in .env.
 * All application settings, AI model choices, and setup flags reside exclusively
 * in the Supabase 'app_settings' table as the Single Source of Truth.
 */
export function writeEnvFiles(vars: EnvVariables) {
  const isWebCwd = fs.existsSync(path.resolve(process.cwd(), "next.config.ts")) || 
                   fs.existsSync(path.resolve(process.cwd(), "next.config.js"));

  const webEnvPath = isWebCwd 
    ? path.resolve(process.cwd(), ".env.local")
    : path.resolve(process.cwd(), "web", ".env.local");

  const rootEnvPath = isWebCwd
    ? path.resolve(process.cwd(), "..", ".env")
    : path.resolve(process.cwd(), ".env");

  const effectiveAnonKey = vars.anonKey || vars.serviceRoleKey;

  // Web environment content (.env.local) - strictly database credentials
  const webLines = [
    `# Generated by JobTrack Setup Wizard`,
    `NEXT_PUBLIC_SUPABASE_URL="${vars.supabaseUrl}"`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY="${effectiveAnonKey}"`,
    `SUPABASE_SERVICE_ROLE_KEY="${vars.serviceRoleKey}"`,
  ];

  // Root environment content (.env)
  const rootLines = [
    `# Generated by JobTrack Setup Wizard`,
    `SUPABASE_URL="${vars.supabaseUrl}"`,
    `SUPABASE_SERVICE_ROLE_KEY="${vars.serviceRoleKey}"`,
  ];

  // Write web/.env.local
  fs.mkdirSync(path.dirname(webEnvPath), { recursive: true });
  fs.writeFileSync(webEnvPath, webLines.join("\n") + "\n", "utf-8");

  // Also update root .env if running from root
  try {
    fs.writeFileSync(rootEnvPath, rootLines.join("\n") + "\n", "utf-8");
  } catch {
    // Ignore if root path not writable
  }

  // Update in-memory environment variables for immediate effect (using dynamic keys to prevent Webpack DefinePlugin inlining)
  const envMap: Record<string, string | undefined> = process.env;
  envMap[["NEXT_PUBLIC", "SUPABASE_URL"].join("_")] = vars.supabaseUrl;
  envMap.SUPABASE_URL = vars.supabaseUrl;
  envMap[["NEXT_PUBLIC", "SUPABASE_ANON_KEY"].join("_")] = effectiveAnonKey;
  envMap.SUPABASE_SERVICE_ROLE_KEY = vars.serviceRoleKey;

  // Clear any legacy in-memory LLM overrides so app_settings remains single source of truth
  delete process.env.LLM_API_KEY;
  delete process.env.GEMINI_API_KEY;
  delete process.env.FIREWORKS_API_KEY;
  delete process.env.OPENAI_API_KEY;
  delete process.env.ANTHROPIC_API_KEY;
  delete process.env.LLM_MODEL;
}
